from DigitalWallet import DigitalWallet
print("===== DIGITAL WALLET QA =====")
w = DigitalWallet()
print("\nTest 1: Normal Transaction")
w.create_account("User1", 1234, 10000)
w.deposit("User1", 5000)
w.withdraw("User1", 1234, 2000)
w.show_balance("User1")
print("\nTest 2: Insufficient Balance")
w.withdraw("User1", 1234, 50000)
print("\nTest 3: Negative Amount")
w.deposit("User1", -1000)
print("\nTest 4: Multiple Failed PINs")
w.withdraw("User1", 1111, 100)
w.withdraw("User1", 2222, 100)
w.withdraw("User1", 3333, 100)
print("\nTest 5: Daily Transaction Limit")
w.withdraw("User1", 1234, 9000)
w.withdraw("User1", 1234, 95000)
print("\nTest 6: Suspicious Transaction")
w.deposit("User1", 100000)
w.withdraw("User1", 1234, 60000)
print("\nTest 7: Duplicate Transaction / Account")
w.create_account("User1", 1234, 5000)
print("\n===== QA COMPLETED =====")
